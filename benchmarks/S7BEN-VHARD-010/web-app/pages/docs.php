<h2>Documentation</h2>

<h3>About This Application</h3>
<p>This is a multi-page PHP web portal. Pages are loaded dynamically using the <code>?page</code> query parameter.</p>

<h3>Available Pages</h3>
<ul>
    <li><strong>home</strong> - Main welcome page</li>
    <li><strong>about</strong> - About this application</li>
    <li><strong>docs</strong> - This documentation page</li>
    <li><strong>contact</strong> - Contact and session information</li>
</ul>

<h3>Features</h3>
<ul>
    <li>Dynamic page routing via URL parameters</li>
    <li>PHP session management</li>
    <li>Apache access logging</li>
</ul>
